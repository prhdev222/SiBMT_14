/**
 * ประเภทของคำถามที่แพทย์ต้นทางส่งเข้ามา
 *
 * ⚠️ resident เป็นคนเลือกตอนตอบ ไม่ใช่แพทย์ต้นทางเลือกตอนถาม
 *
 * สองเหตุผล — คนตอบอ่านคำถามจบแล้วจึงรู้ว่าจริง ๆ ถามอะไร ต่างจากคนถาม
 * ที่ต้องการถาม ไม่ได้ต้องการจัดประเภท และการเก็บฝั่งนี้ไม่ต้องแก้ Google Form
 * ซึ่งทุกครั้งที่แก้ Google จะเขียนหัวคอลัมน์ในชีตทับจนต้องไล่คืนทีละคอลัมน์
 *
 * ⚠️ อยู่ในโค้ด ไม่ได้อยู่ในชีต ต่างจากคลังสูตรยาและรายชื่ออาจารย์
 *
 * รายการนี้เป็นหน่วยวัด ไม่ใช่ข้อมูล — ถ้าแก้ได้ตลอดเวลาโดยไม่มีใครรู้
 * ตัวเลขของปีนี้จะเทียบกับปีที่แล้วไม่ได้ การแก้จึงควรผ่านการ deploy
 * ซึ่งทิ้งร่องรอยไว้ว่าเปลี่ยนเมื่อไรและเพราะอะไร
 *
 * ⚠️ เพิ่มประเภทใหม่ได้ แต่ห้ามแก้ id ของเดิม — เคสเก่าเก็บ id ไว้แล้ว
 */
export interface QuestionType {
  id: string;
  labelTh: string;
}

export const QUESTION_TYPES: QuestionType[] = [
  { id: "REGIMEN_CHOICE", labelTh: "เลือกสูตรยา" },
  { id: "DOSE_TOXICITY", labelTh: "ปรับขนาดยา / จัดการผลข้างเคียง" },
  { id: "REFER_DECISION", labelTh: "ประเมินว่าควรส่งต่อหรือไม่" },
  { id: "TRIAL", labelTh: "สอบถามการศึกษาวิจัย (clinical trial)" },
  { id: "ADMISSION", labelTh: "ขอส่งตัวมารับยาที่ศิริราช" },
  { id: "DIAGNOSIS_WORKUP", labelTh: "การวินิจฉัยหรือการตรวจเพิ่มเติม" },
  { id: "OTHER", labelTh: "อื่น ๆ" },
];

const LABEL_BY_ID = new Map(QUESTION_TYPES.map((t) => [t.id, t.labelTh]));

/**
 * แปลง id เป็นชื่อไทยสำหรับแสดงผล
 *
 * คืน id ดิบเมื่อไม่รู้จัก — เคสเก่าที่บันทึกด้วยรายการรุ่นก่อนยังต้องแสดงได้
 * ไม่ใช่หายไปเงียบ ๆ จากกราฟจนยอดรวมไม่ตรงกับจำนวนเคส
 */
export function questionTypeLabel(id: string): string {
  const key = id.trim();
  if (!key) return "";
  return LABEL_BY_ID.get(key) ?? key;
}
