/**
 * ทำเบอร์โทรให้เทียบกันได้: "081-234-5678" กับ "812345678" (ชีตตัด 0) ต้องตรงกัน
 * ตรรกะเดียวกับ phoneKey_ ใน apps-script/Util.gs — แก้ฝั่งหนึ่งต้องแก้อีกฝั่ง
 *
 * วิธีเทียบ (ก๊อปมาจาก .gs ตรง ๆ): เอาเฉพาะตัวเลข ตัด 0 นำหน้าทิ้ง แล้วใช้
 * 9 ตัวท้าย ครอบคลุมทั้ง 0812345678 / 812345678 / +66812345678 ให้เป็นค่าเดียวกัน
 *
 * ⚠️ ใช้เทียบเท่านั้น ห้ามเอาค่านี้ไปเก็บหรือแสดงผล — มันไม่ใช่เบอร์ที่โทรได้
 * (เดิมไฟล์นี้มีตรรกะของตัวเองที่ไม่ตรงกับ .gs ทำให้เบอร์รูปแบบ +66 หรือ
 * เบอร์ 11+ หลักเทียบไม่ตรงกันระหว่างบอท LINE กับแชทเว็บ — พอร์ตให้ตรงเป๊ะแล้ว)
 */
export function phoneKey(value: string): string {
  const digits = String(value || "").replace(/\D/g, "");
  if (digits.length < 9) return "";
  return digits.replace(/^0+/, "").slice(-9);
}
